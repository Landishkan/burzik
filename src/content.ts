// === Общие типы ===
export interface Option {
  id: string
  text: string
  correct: boolean
  feedback: string
}

export interface ScenarioTask {
  type: 'scenario'
  prompt: string
  options: Option[]
  explanation: string
}

export interface OrderTask {
  type: 'order'
  prompt: string
  steps: string[]
  feedbackCorrect: string
  feedbackWrong: string
}

// 🆕 Новый тип задания: Верно / Неверно
export interface TrueFalseTask {
  type: 'true-false'
  statement: string // Утверждение для оценки
  isTrue: boolean   // Правильный ответ (true или false)
  feedbackCorrect: string // Объяснение, если пользователь ответил верно
  feedbackWrong: string    // Объяснение, если пользователь ошибся
}

// Обновлённый union-тип теперь включает все три варианта
export type Task = ScenarioTask | OrderTask | TrueFalseTask | ChatDialogTask | SwipeTask  | SpotTheFlagTask

// 👇 Добавляем тип Track ПЕРЕД использованием в Lesson
export type Track = 'school' | 'university' | 'both'

export interface Lesson {
  id: string
  title: string
  description: string
  track?: Track // 👈 Опциональное поле: для какого трека урок
  tasks: Task[]
}
// === Новый тип: Раздел (Модуль) ===
export interface Module {
  id: string
  title: string
  description: string
  color: string // цвет шапки раздела (класс Tailwind)
  lessons: Lesson[]
}

