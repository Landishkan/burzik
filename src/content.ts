// === Общие типы ===

export interface Option {
  id: string
  text: string
  correct: boolean
  feedback: string
}

export interface ScenarioTask {
  type: 'scenario'
  prompt: string
  options: Option[]
  explanation: string
}

export interface OrderTask {
  type: 'order'
  prompt: string
  steps: string[]
  feedbackCorrect: string
  feedbackWrong: string
}

export type Task = ScenarioTask | OrderTask

export interface Lesson {
  id: string
  title: string
  description: string
  tasks: Task[]
}

// === Новый тип: Раздел (Модуль) ===
export interface Module {
  id: string
  title: string
  description: string
  color: string // цвет шапки раздела (класс Tailwind)
  lessons: Lesson[]
}

